import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Selected ImageGen PNG paths are supplied in an ignored local source map.
// Real captures must already exist in .playwright-mcp/hero-captures/.
const sourceMapPath = process.argv[2];
if (!sourceMapPath) throw new Error("Usage: node scripts/build-project-heroes.mjs <generated-source-map.json>");
const sources = JSON.parse(await fs.readFile(sourceMapPath, "utf8"));
const art = JSON.parse(await fs.readFile("scripts/project-hero-art-manifest.json", "utf8"));
const captures = JSON.parse(await fs.readFile("scripts/project-hero-captures.json", "utf8"));
const devices = ["desktop", "tablet", "mobile"];
const faDevices = { desktop: "دسکتاپ", tablet: "تبلت", mobile: "موبایل" };
const enDevices = { desktop: "Desktop", tablet: "Tablet", mobile: "Mobile" };
const folder = "public/projects/hero";
await fs.mkdir(folder, { recursive: true });
const registry = {};
const assets = [];

async function writeAsset({ slug, title, device, source, concept, target }) {
  const input = sharp(source);
  const meta = await input.metadata();
  const width = target?.width ?? Math.min(meta.width, 1200);
  const height = target?.height ?? Math.round(meta.height * width / meta.width);
  let buffer;
  let quality = 84;
  do {
    buffer = await sharp(source).resize(width, height, { fit: "fill" }).webp({ quality, effort: 6 }).toBuffer();
    if (buffer.length <= 160000 || quality <= 66) break;
    quality -= 3;
  } while (true);
  const file = `${slug}-${device}.webp`;
  await fs.writeFile(path.join(folder, file), buffer);
  if (device === "desktop") {
    await sharp(source).resize({ width: 720, withoutEnlargement: true }).webp({ quality: 78, effort: 6 }).toFile(path.join(folder, `${slug}-desktop-thumb.webp`));
  }
  const labelFa = concept ? "طرح مفهومی" : "سایت";
  const labelEn = concept ? "design concept" : "live website";
  (registry[slug] ??= []).push({
    src: `/projects/hero/${file}`, width, height,
    alt: {
      fa: `نمای هیروی ${labelFa} ${title.fa} در ${faDevices[device]}`,
      en: `${enDevices[device]} hero view of the ${title.en} ${labelEn}`,
    },
    caption: {
      fa: `${concept ? "طرح مفهومی · " : ""}هیرو در ${faDevices[device]}`,
      en: `${concept ? "Design concept · " : ""}${enDevices[device]} hero`,
    },
  });
  assets.push({ slug, device, file: `/projects/hero/${file}`, width, height, bytes: buffer.length, quality, source: concept ? "built-in image_gen" : "live Playwright capture" });
  console.log(`${file}: ${width}x${height}, ${buffer.length} bytes`);
}

for (const project of captures.projects) {
  for (const device of devices) {
    await writeAsset({ ...project, device, source: `.playwright-mcp/hero-captures/${project.slug}-${device}.png`, concept: false });
  }
}
for (const asset of art.assets) {
  const source = sources[`${asset.slug}:${asset.device}`];
  if (!source) throw new Error(`Missing selected source: ${asset.slug}:${asset.device}`);
  await writeAsset({ ...asset, source, concept: true, target: asset });
}
await fs.writeFile("src/app/components/Projects/hero-views.ts", `// Generated by scripts/build-project-heroes.mjs from approved hero-only assets.\nimport type { ProjectImage } from "./data";\n\nexport const PROJECT_HERO_VIEWS: Record<string, [ProjectImage, ProjectImage, ProjectImage]> = ${JSON.stringify(registry, null, 2)};\n`);
await fs.writeFile("scripts/project-hero-assets.json", `${JSON.stringify({ updatedAt: "2026-10-26", assets }, null, 2)}\n`);
console.log(`Saved ${assets.length} hero views and ${Object.keys(registry).length} desktop thumbnails.`);
